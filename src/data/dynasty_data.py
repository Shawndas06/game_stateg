# Год начала кампании по умолчанию — 1299. Дальше каждый «ход» примерно квартал.
TURNS_PER_YEAR = 4
CAMPAIGN_START_YEAR = 1299


def year_from_turn(turn: int) -> int:
    """Календарный год от номера хода (1 ход ≈ квартал)."""
    return CAMPAIGN_START_YEAR + max(0, turn // TURNS_PER_YEAR)


def get_current_sultan(year: int) -> Sultan:
    """Кто правит в данном году. Возвращает наиболее свежего по reign_start.
    Если до 1299 — возвращает Эртогрула (предок), если после Сулеймана — последнего."""
    candidates = [s for s in DYNASTY_DATA if s.reign_start <= year]
    if not candidates:
        return DYNASTY_DATA[0]
    # Если год попадает в reign — берём именно его. Иначе — последний начатый.
    in_reign = [s for s in candidates if s.reign_start <= year <= s.reign_end]
    if in_reign:
        return in_reign[-1]
    return candidates[-1]


def get_sultan_by_id(sultan_id: str) -> Sultan | None:
    for s in DYNASTY_DATA:
        if s.id == sultan_id:
            return s
    return None
