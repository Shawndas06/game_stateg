def point_in_polygon(lon: float, lat: float, polygon: list[tuple[float, float]]) -> bool:
    """Ray casting — точка внутри полигона (не учитывает дыры)."""
    n = len(polygon)
    if n < 3:
        return False
    inside = False
    j = n - 1
    for i in range(n):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        if ((yi > lat) != (yj > lat)) and (lon < (xj - xi) * (lat - yi) / (yj - yi + 1e-15) + xi):
            inside = not inside
        j = i
    return inside


def is_land(lon: float, lat: float) -> bool:
    """Точка на суше (хотя бы в одном полигоне)."""
    for poly in LAND_POLYGONS:
        if point_in_polygon(lon, lat, poly):
            return True
    return False
